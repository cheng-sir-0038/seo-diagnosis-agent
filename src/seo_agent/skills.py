SEO_SKILLS = {
    tool: Skill(
        name=tool.replace("_", "-"), domain="seo", description=label,
        tools=[tool], prompt_fragment=instruction, metadata={"public_summary": summary},
    )
    for tool, (label, summary, instruction) in _SKILL_SPECS.items()
}


def seo_skills_for_tools(tools: Iterable[str]) -> list[Skill]:
    """Select authored skills for tools available in the current registry."""
    return [SEO_SKILLS[name] for name in dict.fromkeys(tools) if name in SEO_SKILLS]
